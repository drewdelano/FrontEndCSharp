using FrontEndCSharp.Fecsx.Syntax;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;
using System.Text;

namespace FrontEndCSharp.Fecsx;

[Generator(LanguageNames.CSharp)]
public sealed class FecsxGenerator : IIncrementalGenerator
{
    private static readonly SymbolDisplayFormat FullyQualifiedTypeFormat =
        SymbolDisplayFormat.FullyQualifiedFormat.WithMiscellaneousOptions(
            SymbolDisplayFormat.FullyQualifiedFormat.MiscellaneousOptions
            | SymbolDisplayMiscellaneousOptions.IncludeNullableReferenceTypeModifier);

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        context.RegisterPostInitializationOutput(static initializationContext =>
            initializationContext.AddSource(
                "FecsxIntrinsicProps.g.cs",
                SourceText.From(FecsxIntrinsicPropsEmitter.Emit(), Encoding.UTF8)));

        var attributeCasing = context.AnalyzerConfigOptionsProvider.Select(
            static (options, _) => AttributeCasingSetting.Read(options.GlobalOptions));
        context.RegisterSourceOutput(attributeCasing, static (productionContext, setting) =>
        {
            if (setting.InvalidValue != null)
            {
                var descriptor = new DiagnosticDescriptor(
                    "FECSX5001",
                    "Invalid FECSX project configuration",
                    "MSBuild property '" + FecsxAttributeNaming.ProjectPropertyName
                        + "' must be either 'camelCase' or 'PascalCase', but was '{0}'",
                    "FECSX",
                    DiagnosticSeverity.Error,
                    true);
                productionContext.ReportDiagnostic(Diagnostic.Create(
                    descriptor,
                    Location.None,
                    setting.InvalidValue));
            }
        });

        var documents = context.AdditionalTextsProvider
            .Where(static file => file.Path.EndsWith(".fecsx", StringComparison.OrdinalIgnoreCase))
            .Select(static (file, cancellationToken) => Parse(file, cancellationToken));
        context.RegisterSourceOutput(
            documents.Combine(context.CompilationProvider).Combine(attributeCasing),
            static (productionContext, input) =>
            {
                if (input.Right.InvalidValue == null)
                {
                    Emit(
                        productionContext,
                        input.Left.Left,
                        input.Left.Right,
                        input.Right.Casing);
                }
            });
    }

    private static GeneratedDocument Parse(AdditionalText file, CancellationToken cancellationToken)
    {
        var text = file.GetText(cancellationToken) ?? SourceText.From(string.Empty, Encoding.UTF8);
        return new GeneratedDocument(file.Path, text, FecsxRenderDocumentParser.Parse(text.ToString(), file.Path));
    }

    private static void Emit(
        SourceProductionContext context,
        GeneratedDocument document,
        Compilation compilation,
        FecsxAttributeCasing attributeCasing)
    {
        var diagnostics = FecsxDocumentDiagnostics.GetDiagnostics(document.Syntax, attributeCasing);

        foreach (var diagnostic in diagnostics)
        {
            var descriptor = new DiagnosticDescriptor(diagnostic.Id, "Invalid FECSX render document", diagnostic.Message, "FECSX", DiagnosticSeverity.Error, true);
            var span = new TextSpan(diagnostic.Span.Start, diagnostic.Span.Length);
            context.ReportDiagnostic(Diagnostic.Create(descriptor, Location.Create(document.Path, span, document.Text.Lines.GetLinePositionSpan(span))));
        }

        if (diagnostics.Count != 0 || document.Syntax.DefaultComponent?.Body == null)
        {
            return;
        }

        var componentName = document.Syntax.FacadeName;
        var propsTypes = ResolvePropsTypes(compilation, document.Syntax, document.Path, context.CancellationToken);
        context.AddSource(CreateHintName(document.Path, componentName), SourceText.From(GenerateComponent(document.Syntax, componentName, document.Path, propsTypes), Encoding.UTF8));
    }

    private static string GenerateComponent(
        FecsxRenderDocumentSyntax syntax,
        string componentName,
        string path,
        IReadOnlyDictionary<string, string> propsTypes)
    {
        var builder = new StringBuilder();
        builder.AppendLine("// <auto-generated />");
        builder.AppendLine("#nullable enable");
        builder.AppendLine("#line hidden");
        if (!string.IsNullOrWhiteSpace(syntax.Preamble)) builder.AppendLine(syntax.Preamble.TrimEnd());
        builder.Append("public static class ").Append(componentName).AppendLine().AppendLine("{");
        EmitFacadeMembers(builder, syntax, syntax.DefaultComponent!, path, "    ", "RenderDefault", propsTypes);
        foreach (var component in syntax.Components.Where(component =>
            !string.Equals(component.Name, "Default", StringComparison.Ordinal)))
        {
            builder.Append("    public static class ").Append(component.Name).AppendLine().AppendLine("    {");
            EmitFacadeMembers(builder, syntax, component, path, "        ", "Render", propsTypes);
            builder.AppendLine("    }");
        }
        builder.AppendLine("}");
        return builder.ToString();
    }

    private static void EmitFacadeMembers(
        StringBuilder builder,
        FecsxRenderDocumentSyntax syntax,
        FecsxComponentDeclarationSyntax component,
        string path,
        string indent,
        string renderMethodName,
        IReadOnlyDictionary<string, string> propsTypes)
    {
        var propsType = propsTypes[component.Name];
        builder.Append(indent).Append("private static readonly global::Interop.JS.React.ReactComponent<").Append(propsType).Append("> s_component = global::Interop.JS.React.React.Component<").Append(propsType).Append('>').Append('(').Append(renderMethodName).AppendLine(");");
        builder.Append(indent).Append("public static global::Interop.JS.React.ReactComponent<").Append(propsType).AppendLine("> Component => s_component;");
        builder.Append(indent).Append("public static global::Interop.JS.React.ReactElement Create(global::System.Action<").Append(propsType).AppendLine("> configure, params global::Interop.JS.React.ReactNode[] children)");
        builder.Append(indent).AppendLine("{").Append(indent).Append("    var props = new ").Append(propsType).AppendLine("();").Append(indent).AppendLine("    configure(props);").Append(indent).AppendLine("    return global::Interop.JS.React.React.CreateElement(s_component, props, children);").Append(indent).AppendLine("}");
        builder.Append(indent).Append("private static global::Interop.JS.React.ReactNode ").Append(renderMethodName).Append('(').Append(propsType).Append(' ').Append(component.PropsParameterName).Append(", global::Interop.JS.React.ReactNode[] ").Append(component.ChildrenParameterName).AppendLine(") =>");
        var expressionPrefix = syntax.Source.Substring(
            component.ExpressionOffset,
            component.BodyOffset - component.ExpressionOffset);
        var expressionSuffix = syntax.Source.Substring(
            component.BodyEnd,
            component.ExpressionEnd - component.BodyEnd);
        builder.Append("#line ").Append(GetLine(syntax.Source, component.ExpressionOffset)).Append(' ').AppendLine(FormatLineDirectivePath(path));
        builder.Append(indent).Append("    ").Append(expressionPrefix).Append(FecsxLowerer.Lower(
            component.Body!,
            expression => MapAnonymousFunctionExpression(expression, syntax, component, path))).Append(expressionSuffix).AppendLine(";").AppendLine("#line default").AppendLine("#line hidden");
    }

    private static string MapAnonymousFunctionExpression(
        FecsxExpressionSyntax expression,
        FecsxRenderDocumentSyntax syntax,
        FecsxComponentDeclarationSyntax component,
        string path)
    {
        var parsedExpression = expression.Expression;
        if (parsedExpression == null
            || (parsedExpression is not AnonymousFunctionExpressionSyntax
                && !parsedExpression.DescendantNodes().OfType<AnonymousFunctionExpressionSyntax>().Any()))
        {
            return expression.Text;
        }

        var expressionLine = GetLine(syntax.Source, component.BodyOffset + expression.ContentSpan.Start);
        var bodyLine = GetLine(syntax.Source, component.BodyOffset);
        return "\n"
            + "#line " + expressionLine + " " + FormatLineDirectivePath(path) + "\n"
            + expression.Text + "\n"
            + "#line " + bodyLine + " " + FormatLineDirectivePath(path) + "\n";
    }

    private static IReadOnlyDictionary<string, string> ResolvePropsTypes(
        Compilation compilation,
        FecsxRenderDocumentSyntax syntax,
        string path,
        CancellationToken cancellationToken)
    {
        const string probeClassName = "__FrontEndCSharpFecsxPropsTypeProbe";
        var source = new StringBuilder(syntax.Preamble.TrimEnd());
        var probeStart = source.Length;
        source.AppendLine().Append("internal static class ").Append(probeClassName).AppendLine().AppendLine("{");
        for (var index = 0; index < syntax.Components.Count; index++)
        {
            source.Append("    private static void Resolve").Append(index).Append('(')
                .Append(syntax.Components[index].PropsTypeName).AppendLine(" value) { }");
        }
        source.AppendLine("}");

        var parseOptions = compilation.SyntaxTrees.FirstOrDefault()?.Options as CSharpParseOptions
            ?? CSharpParseOptions.Default.WithLanguageVersion(LanguageVersion.Latest);
        var tree = CSharpSyntaxTree.ParseText(
            source.ToString(),
            parseOptions,
            path + ".props-probe.cs",
            cancellationToken: cancellationToken);
        var probeCompilation = compilation.AddSyntaxTrees(tree);
        var semanticModel = probeCompilation.GetSemanticModel(tree, ignoreAccessibility: true);
        var probe = tree.GetRoot(cancellationToken).DescendantNodes().OfType<ClassDeclarationSyntax>()
            .Single(declaration => declaration.SpanStart >= probeStart);
        var methods = probe.Members.OfType<MethodDeclarationSyntax>().ToArray();
        var result = new Dictionary<string, string>(StringComparer.Ordinal);

        for (var index = 0; index < syntax.Components.Count; index++)
        {
            var component = syntax.Components[index];
            var typeSyntax = methods[index].ParameterList.Parameters[0].Type!;
            var symbol = semanticModel.GetTypeInfo(typeSyntax, cancellationToken).Type;
            result.Add(
                component.Name,
                symbol == null || symbol.TypeKind == TypeKind.Error
                    ? QualifyType(component.PropsTypeName, syntax.NamespaceName)
                    : symbol.ToDisplayString(FullyQualifiedTypeFormat));
        }

        return result;
    }

    private static string QualifyType(string name, string? namespaceName)
    {
        if (name.StartsWith("global::", StringComparison.Ordinal) || name.IndexOfAny(new[] { '<', '[', '?' }) >= 0) return name;
        return "global::" + (name.Contains(".") || string.IsNullOrWhiteSpace(namespaceName) ? name : namespaceName + "." + name);
    }

    private static int GetLine(string source, int position)
    {
        var line = 1;
        for (var index = 0; index < position && index < source.Length; index++) if (source[index] == '\n') line++;
        return line;
    }

    private static string FormatLineDirectivePath(string path) =>
        "\"" + path.Replace("\"", "\\\"") + "\"";

    private static string CreateHintName(string path, string componentName)
    {
        var hash = 2166136261u;
        foreach (var character in path) hash = (hash ^ character) * 16777619u;
        return componentName + "." + hash.ToString("x8") + ".fecsx.g.cs";
    }

    private sealed class GeneratedDocument
    {
        public GeneratedDocument(string path, SourceText text, FecsxRenderDocumentSyntax syntax) { Path = path; Text = text; Syntax = syntax; }
        public string Path { get; }
        public SourceText Text { get; }
        public FecsxRenderDocumentSyntax Syntax { get; }
    }

    private readonly struct AttributeCasingSetting
    {
        private AttributeCasingSetting(
            FecsxAttributeCasing casing,
            string? invalidValue)
        {
            Casing = casing;
            InvalidValue = invalidValue;
        }

        public FecsxAttributeCasing Casing { get; }
        public string? InvalidValue { get; }

        public static AttributeCasingSetting Read(
            Microsoft.CodeAnalysis.Diagnostics.AnalyzerConfigOptions options)
        {
            if (!options.TryGetValue(FecsxAttributeNaming.AnalyzerConfigPropertyName, out var value))
            {
                return new AttributeCasingSetting(FecsxAttributeCasing.CamelCase, null);
            }
            if (FecsxAttributeNaming.TryParse(value, out var casing))
            {
                return new AttributeCasingSetting(casing, null);
            }

            return new AttributeCasingSetting(FecsxAttributeCasing.CamelCase, value);
        }
    }
}
