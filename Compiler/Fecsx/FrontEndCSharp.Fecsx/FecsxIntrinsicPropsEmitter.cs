using System.Text;

namespace FrontEndCSharp.Fecsx;

internal static class FecsxIntrinsicPropsEmitter
{
    public static string Emit()
    {
        var builder = new StringBuilder();
        builder.AppendLine("// <auto-generated />")
            .AppendLine("#nullable enable")
            .AppendLine("#line hidden")
            .AppendLine("namespace FrontEndCSharp.Fecsx.Html;")
            .AppendLine()
            .AppendLine("public abstract class HtmlProps")
            .AppendLine("{");
        EmitPropertyDeclarations(builder, IntrinsicElementSchema.GlobalProperties);
        builder.AppendLine("    protected void ApplyGlobal(global::Interop.JS.React.ReactProps props)")
            .AppendLine("    {");
        foreach (var property in IntrinsicElementSchema.GlobalProperties)
        {
            EmitPropertyConversion(builder, property, "this");
        }
        builder.AppendLine("    }");
        builder.AppendLine("}");

        foreach (var element in IntrinsicElementSchema.Elements)
        {
            builder.AppendLine()
                .Append("public sealed class ").Append(element.PropsTypeName).AppendLine(" : HtmlProps")
                .AppendLine("{");
            EmitPropertyDeclarations(builder, element.DeclaredProperties);
            builder.Append("    public static global::Interop.JS.React.ReactProps Create(global::System.Action<")
                .Append(element.PropsTypeName).AppendLine("> configure)")
                .AppendLine("    {")
                .Append("        var values = new ").Append(element.PropsTypeName).AppendLine("();")
                .AppendLine("        configure(values);")
                .AppendLine("        var props = global::Interop.JS.React.ReactProps.Create();")
                .AppendLine("        values.ApplyGlobal(props);");
            foreach (var property in element.DeclaredProperties)
            {
                EmitPropertyConversion(builder, property, "values");
            }

            builder.AppendLine("        return props;")
                .AppendLine("    }")
                .AppendLine("}");
        }

        return builder.ToString();
    }

    private static void EmitPropertyDeclarations(StringBuilder builder, IEnumerable<IntrinsicPropertyDescriptor> properties)
    {
        foreach (var property in properties)
        {
            if (property.Kind == IntrinsicPropertyKind.Boolean || property.Kind == IntrinsicPropertyKind.Number)
            {
                var type = GetManagedType(property.Kind);
                var fieldName = "__" + char.ToLowerInvariant(property.PropertyName[0]) + property.PropertyName.Substring(1);
                builder.Append("    private ").Append(type).Append(' ').Append(fieldName).AppendLine(";")
                    .Append("    private bool __has").Append(property.PropertyName).AppendLine(";")
                    .Append("    public ").Append(type).Append(' ').Append(property.PropertyName).AppendLine()
                    .AppendLine("    {")
                    .Append("        get => ").Append(fieldName).AppendLine(";")
                    .Append("        set { ").Append(fieldName).Append(" = value; __has").Append(property.PropertyName).AppendLine(" = true; }")
                    .AppendLine("    }");
            }
            else
            {
                builder.Append("    public ").Append(GetManagedType(property.Kind)).Append(' ')
                    .Append(property.PropertyName).AppendLine(" { get; set; }");
            }
        }
    }

    private static void EmitPropertyConversion(StringBuilder builder, IntrinsicPropertyDescriptor property, string owner)
    {
        var propertyAccess = owner + "." + property.PropertyName;
        switch (property.Kind)
        {
            case IntrinsicPropertyKind.String:
                builder.Append("        if (").Append(propertyAccess).Append(" != null) props.SetString(\"")
                    .Append(property.ReactName).Append("\", ").Append(propertyAccess).AppendLine(");");
                break;
            case IntrinsicPropertyKind.Boolean:
                builder.Append("        if (").Append(owner).Append(".__has").Append(property.PropertyName).Append(") props.SetBoolean(\"")
                    .Append(property.ReactName).Append("\", ").Append(propertyAccess).AppendLine(");");
                break;
            case IntrinsicPropertyKind.Number:
                builder.Append("        if (").Append(owner).Append(".__has").Append(property.PropertyName).Append(") props.SetNumber(\"")
                    .Append(property.ReactName).Append("\", ").Append(propertyAccess).AppendLine(");");
                break;
            case IntrinsicPropertyKind.EventHandler:
                builder.Append("        if (").Append(propertyAccess).Append(" != null) props.SetEventHandler(\"")
                    .Append(property.ReactName).Append("\", ").Append(propertyAccess).AppendLine(");");
                break;
            default:
                throw new InvalidOperationException($"Unknown intrinsic property kind '{property.Kind}'.");
        }
    }

    private static string GetManagedType(IntrinsicPropertyKind kind)
    {
        switch (kind)
        {
            case IntrinsicPropertyKind.String:
                return "string?";
            case IntrinsicPropertyKind.Boolean:
                return "bool";
            case IntrinsicPropertyKind.Number:
                return "double";
            case IntrinsicPropertyKind.EventHandler:
                return "global::System.Action<global::Interop.JS.Browser.DomEvent>?";
            default:
                throw new InvalidOperationException($"Unknown intrinsic property kind '{kind}'.");
        }
    }
}
